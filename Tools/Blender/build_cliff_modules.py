def normal(verts, face):
    a,b,c=(verts[i] for i in face)
    u=[b[i]-a[i] for i in range(3)]; v=[c[i]-a[i] for i in range(3)]
    w=(u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0])
    mag=sqrt(sum(x*x for x in w))
    assert mag>1e-6, face
    return tuple(x/mag for x in w)


def build(spec):
    outline=spec['outline']; n=len(outline); h=spec['height']; dx,dz=spec['offset']
    b=spec['breaks']; shelf=spec['shelf']; cap=spec['cap']
    assert len(b)==n
    # Positive edge cross products mean the origin sees every outline edge.
    # The same property is checked for all cap rings around their own centers.
    assert all(x*z2-z*x2>0 for (x,z),(x2,z2) in zip(outline,outline[1:]+outline[:1]))
    # A low talus, lower wall, uneven shelf, upper wall and a level crown.
    # Height variation stops at the crown so there is no radial fan shading.
    rings=[
        (1,0,0,0,0),
        (.95,.25,.09,.3,.18),
        (.92,.45,.34,.45,.65),
        (.87,.65,.58,.7,.7),
        (shelf,1.0,.62,.85,.7),
        (shelf-.035,.85,.78,.95,.5),
        (cap+.07,.5,.91,1,.35),
        (cap,.4,1,1,0),
    ]
    verts=[]
    for scale,amp,y,shift,vertical in rings:
        ring=[(x*(scale+amp*b[i])+dx*shift, h*(y+vertical*b[i]), z*(scale+amp*b[i])+dz*shift) for i,(x,z) in enumerate(outline)]
        local=[(x-dx*shift,z-dz*shift) for x,_,z in ring]
        assert all(x*z2-z*x2>0 for (x,z),(x2,z2) in zip(local,local[1:]+local[:1]))
        verts.extend(ring)
    assert all(verts[k*n+i][1]<verts[(k+1)*n+i][1] for k in range(len(rings)-1) for i in range(n))
    faces={g:[] for g in PALETTE}
    for k,group in enumerate(('Foot','Wall','Wall','Crown','Wall','Wall','Crown')):
        for i in range(n):
            j=(i+1)%n; a,b1,c,d=k*n+i,(k+1)*n+i,(k+1)*n+j,k*n+j
            faces[group].extend(((a,b1,c),(a,c,d)))
    bottom=len(verts); verts.append((0,0,0))
    top=len(verts); verts.append((dx,h,dz))
    for i in range(n):
        j=(i+1)%n
        faces['Foot'].append((bottom,i,j))
        faces['Crown'].append((top,(len(rings)-1)*n+j,(len(rings)-1)*n+i))
    all_faces=[f for fs in faces.values() for f in fs]
    edge=Counter((a,b) for f in all_faces for a,b in zip(f,f[1:]+f[:1]))
    assert all(count==1 and edge[b,a]==1 for (a,b),count in edge.items())
    for f in all_faces: normal(verts,f)
    for f in faces['Crown'][-n:]: assert normal(verts,f)[1]>.99999
    for f in faces['Foot'][-n:]: assert normal(verts,f)[1]<-.99999
    return verts,faces


def export_obj(name,verts,faces):
    for group,fs in faces.items():
        used=sorted({i for f in fs for i in f}); remap={v:i+1 for i,v in enumerate(used)}
        lines=['# Authored cliff module; generated by build_cliff_modules.py',f'o {name}_{group}','s off']
        lines+=['v %.6f %.6f %.6f'%verts[i] for i in used]
        lines+=['vn %.8f %.8f %.8f'%normal(verts,f) for f in fs]
        for i,f in enumerate(fs,1): lines.append('f '+' '.join(f'{remap[v]}//{i}' for v in f))
        (OUT/f'{name}_{group}.obj').write_text('\n'.join(lines)+'\n',encoding='utf-8')


def main():
    OUT.mkdir(parents=True,exist_ok=True)
    models={name:build(spec) for name,spec in SPECS.items()}
    for name,(verts,faces) in models.items():
        export_obj(name,verts,faces)
        print(f'{name}: {len(verts)} vertices, {sum(map(len,faces.values()))} triangles; closed topology')
    try:
        import bpy
    except ImportError:
        return
    bpy.ops.object.select_all(action='SELECT'); bpy.ops.object.delete(use_global=False)
    mats={}
    def linear(c):
        s=c/255; return s/12.92 if s<=.04045 else ((s+.055)/1.055)**2.4
    for group,rgb in PALETTE.items():
        mat=bpy.data.materials.new(group); mat.diffuse_color=tuple(linear(c) for c in rgb)+(1,); mats[group]=mat
    for i,(name,(verts,faces)) in enumerate(models.items()):
        mesh=bpy.data.meshes.new(name)
        mesh.from_pydata([(x,-z,y) for x,y,z in verts],[],[f for fs in faces.values() for f in fs]); mesh.update()
        obj=bpy.data.objects.new(name,mesh); bpy.context.collection.objects.link(obj)
        # Layout for authoring review only; local origins remain at ground center.
        obj.location=(i*1200,0,0)
        cursor=0
        for idx,(group,fs) in enumerate(faces.items()):
            mesh.materials.append(mats[group])
            for p in mesh.polygons[cursor:cursor+len(fs)]: p.material_index=idx; p.use_smooth=False
            cursor+=len(fs)
    dest=ROOT/'Resources/Blender/CliffModules.blend'; dest.parent.mkdir(parents=True,exist_ok=True)
    bpy.ops.wm.save_as_mainfile(filepath=str(dest))


if __name__=='__main__': main()
