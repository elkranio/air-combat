def norm(v,f):
    a,b,c=(v[i] for i in f); u=[b[i]-a[i] for i in range(3)]; w=[c[i]-a[i] for i in range(3)]
    n=(u[1]*w[2]-u[2]*w[1],u[2]*w[0]-u[0]*w[2],u[0]*w[1]-u[1]*w[0]); m=sqrt(sum(x*x for x in n)); assert m>1e-6
    return tuple(x/m for x in n)


def build(spec):
    name,(cx,cz),h,tone,(dx,dz),(sx,sz),outline,chips=spec
    n=len(outline); assert len(chips)==n
    assert all(x*z2-z*x2>0 for (x,z),(x2,z2) in zip(outline,outline[1:]+outline[:1]))
    # No shared horizontal shelf. Long near-vertical block faces with localized
    # corner fractures: the shoulder starts at different heights per corner.
    verts=[]
    for ring in range(3):
        for i,(x,z) in enumerate(outline):
            top=h+sx*x+sz*z
            if ring==0: k=1.0; t=0; y=0
            elif ring==1: k=1.0+(.035 if i%4==1 else -.025 if i%4==2 else 0); t=.72; y=max(top*.53,top-5-chips[i]*1.8)
            else: k=.91-(.10 if chips[i]>=8 else .035 if chips[i]>=5 else 0); t=1; y=top
            verts.append((cx+x*k+dx*t,y,cz+z*k+dz*t))
    faces=[]
    for ring in range(2):
        for i in range(n):
            j=(i+1)%n; a,b,c,d=ring*n+i,(ring+1)*n+i,(ring+1)*n+j,ring*n+j
            faces.extend(((a,b,c),(a,c,d)))
    bot=len(verts); verts.append((cx,0,cz)); top=len(verts); verts.append((cx+dx,h,cz+dz))
    # Top is gently sloped. Re-evaluate heights at actual cap coordinates so
    # every cap triangle is coplanar and does not produce fan shading.
    for i in range(2*n,3*n):
        x,_,z=verts[i]; verts[i]=(x,h+sx*(x-cx-dx)+sz*(z-cz-dz),z)
        assert verts[i][1]>verts[i-n][1]
    for i in range(n):
        j=(i+1)%n; faces.extend(((bot,i,j),(top,2*n+j,2*n+i)))
    edges=Counter((a,b) for f in faces for a,b in zip(f,f[1:]+f[:1])); assert all(v==1 and edges[b,a]==1 for (a,b),v in edges.items())
    for f in faces: norm(verts,f)
    assert all(norm(verts,f)[1]>.9 for f in faces[-2*n+1::2])
    return verts,faces,tone


def main():
    OUT.mkdir(parents=True,exist_ok=True)
    models=[]
    for spec in SPECS:
        name=spec[0]; v,f,tone=build(spec); models.append((name,v,f,tone))
        lines=['# CL05 authored solid; Unity Y-up; generated by build_cl05_test_rock.py',f'o CL05_{name}','s off']
        lines+=['v %.6f %.6f %.6f'%p for p in v]; lines+=['vn %.8f %.8f %.8f'%norm(v,face) for face in f]
        for i,face in enumerate(f,1): lines.append('f '+' '.join(f'{j+1}//{i}' for j in face))
        (OUT/f'CL05_{name}.obj').write_text('\n'.join(lines)+'\n',encoding='utf-8')
        print(name,len(v),len(f),'closed solid')
    try: import bpy
    except ImportError: return
    bpy.ops.object.select_all(action='SELECT'); bpy.ops.object.delete(use_global=False)
    mats=[]
    def linear(c):
        s=c/255; return s/12.92 if s<=.04045 else ((s+.055)/1.055)**2.4
    for i,rgb in enumerate(PALETTE):
        mat=bpy.data.materials.new(f'CL05_Stone_{i}'); mat.diffuse_color=tuple(linear(c) for c in rgb)+(1,); mats.append(mat)
    for name,v,f,tone in models:
        mesh=bpy.data.meshes.new(name); mesh.from_pydata([(x,-z,y) for x,y,z in v],[],f); mesh.update(); mesh.materials.append(mats[tone]); obj=bpy.data.objects.new(name,mesh); bpy.context.collection.objects.link(obj)
    dest=ROOT/'Resources/Blender/CL05_TestRock.blend'; dest.parent.mkdir(parents=True,exist_ok=True); bpy.ops.wm.save_as_mainfile(filepath=str(dest))

if __name__=='__main__': main()
