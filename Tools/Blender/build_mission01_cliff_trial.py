"""Standalone visual trial, Unity Y-up OBJ; optionally save editable Blender source.
python Tools/Blender/build_mission01_cliff_trial.py
blender --background --factory-startup --python Tools/Blender/build_mission01_cliff_trial.py
"""
from pathlib import Path
from collections import Counter
from math import sqrt

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'Assets/_Project/Art/Environment/Mission01_FirstSortie/CliffTrial'
PALETTE = {'Foot': (165,145,122), 'Wall': (112,92,77), 'Crown': (160,143,123)}
# Counterclockwise XZ outline. Eight extra corners are authored breaks in the
# wall silhouette, not uniform subdivision. Retain the original outer envelope.
outline = [(160,-18),(157,9),(151,35),(110,79),(77,84),(44,95),
           (7,83),(-31,80),(-75,77),(-107,88),(-155,45),(-163,17),
           (-170,-12),(-139,-65),(-105,-76),(-65,-88),(10,-72),
           (48,-87),(85,-91),(144,-56),(147,-36)]
n = len(outline)
# Each level has its own radial profile. Continuous rock faces are broken by
# large buttresses; the ledge varies from broad shelf to a near-vanishing lip.
# Keep vertical ordering even on the lowest notches.
foot = [12,14,15,12,16,18,14,13,16,15,12,14,15,12,14,16,12,13,15,12,14]
wall_top = [93,96,101,95,89,103,96,91,95,98,86,92,97,90,96,103,92,89,98,93,95]
ledge_scale = [.72,.77,.83,.74,.70,.73,.81,.75,.69,.74,.82,.76,.70,.73,.80,.71,.76,.83,.71,.74,.80]
upper_top = [136,141,146,137,134,149,139,133,142,145,129,137,141,132,141,149,135,131,143,137,140]
crown = [142,146,150,144,139,154,145,140,148,149,137,143,147,140,146,154,143,139,149,143,145]

def uniform(value):
    return [value] * n

# The two additional rings are genuine changes in the side profile, not coplanar
# triangles. Most of both tiers remain steep, with no extra material bands.
levels = [
    (uniform(1.0),0,0,[0]*n),
    (uniform(.91),0,0,foot),
    ([.89,.91,.88,.86,.92,.89,.87,.90,.93,.87,.90,.88,.92,.88,.90,.89,.86,.92,.89,.87,.90],
     -1,1,[50,43,56,48,60,54,47,58,49,55,42,54,48,57,49,61,45,53,56,47,52]),
    (uniform(.86),-3,1,wall_top),
    (ledge_scale,-5,3,[y+3+(i%3) for i,y in enumerate(wall_top)]),
    ([s-.025+(i%3-1)*.012 for i,s in enumerate(ledge_scale)],-6,4,
     [116,123,126,117,112,128,121,113,123,125,110,118,122,113,121,129,116,111,124,118,120]),
    ([min(.68,s-.07) for s in ledge_scale],-8,6,upper_top),
    ([min(.61,s-.055) for s in ledge_scale],-8,6,crown),
]
verts = [(x*scales[i]+ox, ys[i], z*scales[i]+oz)
         for scales,ox,oz,ys in levels for i,(x,z) in enumerate(outline)]
faces = {g: [] for g in PALETTE}

def add(group,a,b,c):
    faces[group].append((a,b,c))

for k,group in enumerate(('Foot','Wall','Wall','Crown','Wall','Wall','Crown')):
    for i in range(n):
        j=(i+1)%n
        a,b,c,d=k*n+i,(k+1)*n+i,(k+1)*n+j,k*n+j
        add(group,a,b,c); add(group,a,c,d)
# top and bottom fan, wound outward
bottom=len(verts); verts.append((0,0,0))
top=len(verts); verts.append((-8,151,6))
for i in range(n):
    j=(i+1)%n
    add('Foot',bottom,i,j)
    add('Crown',top,(len(levels)-1)*n+j,(len(levels)-1)*n+i)

def normal(f):
    a,b,c=(verts[i] for i in f)
    u=[b[i]-a[i] for i in range(3)]; v=[c[i]-a[i] for i in range(3)]
    w=(u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0])
    mag=sqrt(sum(x*x for x in w)); assert mag>1e-6
    return tuple(x/mag for x in w)

# Closed combined topology and consistently directed shared edges.
edge=Counter((a,b) for fs in faces.values() for f in fs for a,b in zip(f,f[1:]+f[:1]))
assert all(count==1 and edge[b,a]==1 for (a,b),count in edge.items())
OUT.mkdir(parents=True,exist_ok=True)
for group,fs in faces.items():
    used=sorted({i for f in fs for i in f}); remap={v:i+1 for i,v in enumerate(used)}
    lines=['# Mission01 cliff trial; generated by build_mission01_cliff_trial.py',f'o CliffTrial_{group}','s off']
    lines += ['v %.6f %.6f %.6f'%verts[i] for i in used]
    lines += ['vn %.8f %.8f %.8f'%normal(f) for f in fs]
    for i,f in enumerate(fs,1): lines.append('f '+' '.join(f'{remap[v]}//{i}' for v in f))
    (OUT/f'CliffTrial_{group}.obj').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print(f'Cliff trial: {len(verts)} vertices, {sum(map(len,faces.values()))} triangles, closed combined topology')
try:
    import bpy
except ImportError:
    bpy=None
if bpy is not None:
    bpy.ops.object.select_all(action='SELECT'); bpy.ops.object.delete(use_global=False)
    mesh=bpy.data.meshes.new('CliffTrial'); all_faces=[f for fs in faces.values() for f in fs]
    # Unity Y-up to Blender Z-up, preserving winding.
    mesh.from_pydata([(x,-z,y) for x,y,z in verts],[],all_faces); mesh.update()
    obj=bpy.data.objects.new('CliffTrial',mesh); bpy.context.collection.objects.link(obj)
    cursor=0
    for idx,(group,fs) in enumerate(faces.items()):
        mat=bpy.data.materials.new(group)
        def linear(c):
            s=c/255; return s/12.92 if s<=.04045 else ((s+.055)/1.055)**2.4
        mat.diffuse_color=tuple(linear(c) for c in PALETTE[group])+(1,)
        mesh.materials.append(mat)
        for p in mesh.polygons[cursor:cursor+len(fs)]: p.material_index=idx; p.use_smooth=False
        cursor+=len(fs)
    bpy.context.view_layer.objects.active=obj; obj.select_set(True)
    dest=ROOT/'Resources/Blender/Mission01_CliffTrial.blend'; dest.parent.mkdir(parents=True,exist_ok=True)
    bpy.ops.wm.save_as_mainfile(filepath=str(dest))
